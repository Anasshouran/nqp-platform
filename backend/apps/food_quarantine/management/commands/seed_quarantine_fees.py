ORDER_MAP = {
    'SHIP_INSPECTION': 1,
    'HEALTH_SERVICES': 2,
    'VACCINATION': 3,
    'MEDICAL_FITNESS': 4,
    'PEST_CONTROL': 5,
    'CERTIFICATE': 6,
    'VIOLATION': 7,
    'FOOD_IMPORT': 8,
    'FOOD_EXPORT': 9,
    'UNLOADING': 10,
    'MICRO_TEST': 11,
    'CHEMICAL_TEST': 12,
}


class Command(BaseCommand):
    help = 'بذر تعرفة رسوم الكرنتينة لعام 2025 (86 بندًا)'

    def handle(self, *args, **options):
        QuarantineFee.objects.filter(year=YEAR).delete()
        rows = []
        for code, category, name_ar, sdg, usd, note in FEES:
            rows.append(QuarantineFee(
                code=code,
                category=category,
                name_ar=name_ar,
                amount_sdg=sdg,
                amount_usd=usd,
                currency_note=note,
                order=ORDER_MAP.get(category, 0),
                year=YEAR,
                is_active=True,
            ))
        QuarantineFee.objects.bulk_create(rows)
        self.stdout.write(self.style.SUCCESS(
            f'تم بذر تعرفة الكرنتينة {YEAR}: {len(rows)} بندًا عبر 12 قسمًا.'
        ))